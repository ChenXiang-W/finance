function getOrCreateSessionId() {
  var sid = localStorage.getItem('fraud_session_id');
  if (!sid) {
    sid = 'session_' + Date.now() + '_' + Math.random().toString(36).slice(2, 8);
    localStorage.setItem('fraud_session_id', sid);
  }
  return sid;
}
